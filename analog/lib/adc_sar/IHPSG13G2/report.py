#!/usr/bin/env python3
"""Archive completed evidence and update the measured tables in pnr.md.

Functional failures are reportable results. Incomplete runs, changed geometry,
changed simulation inputs and absent evidence cannot become PASS rows.
"""
import argparse,csv,gzip,json,shutil
from pathlib import Path
from provenance import digest,verify

MARKER='<!-- measured-results: generated by report.py -->'
LEVELS=[.85,1.15,1.45,1.75,2.05]

def table(headers,rows):
    rows=[[str(v) for v in r] for r in [headers,*rows]]
    widths=[max(len(r[i]) for r in rows) for i in range(len(headers))]
    line=lambda r:'  '.join(v.ljust(n) for v,n in zip(r,widths)).rstrip()
    return '\n```text\n'+line(rows[0])+'\n'+line(['-'*n for n in widths])+'\n'+'\n'.join(map(line,rows[1:]))+'\n```\n'

def completed_case(path,netlist):
    checks=json.loads((path/'checks.json').read_text())
    if checks['status'] not in ('PASS','FAIL') or not checks['native']['complete']:
        raise ValueError('incomplete electrical evidence: '+str(path))
    verify(json.loads((path/'inputs.json').read_text()))
    manifest=json.loads((path/'manifest.json').read_text())
    verify(manifest['artifact_sha256'])
    binding=Path(checks['command'][3]).parent
    if (binding/'diagnostic.json').exists():
        raise ValueError('diagnostic binding has no matching physical geometry')
    lowering=json.loads((binding/'lowering.json').read_text())
    if lowering['input_netlist_sha256']!=digest(netlist):
        raise ValueError('simulation belongs to another netlist')
    rows=checks['measurements']['samples']
    if [r['input_V'] for r in rows]!=LEVELS:raise ValueError('incomplete five-input matrix')
    return checks,lowering

def run(a):
    out=a.output.resolve();out.mkdir(parents=True,exist_ok=True)
    physical=json.loads((a.physical/'checks.json').read_text())
    if physical['status']!='PASS':raise ValueError('only verified geometry may replace the delivered GDS')
    verify(physical['source_sha256'])
    verify({str(a.physical/p):h for p,h in physical['artifact_sha256'].items()})
    annotation=json.loads((a.backannotation/'backannotation.json').read_text())
    verify(annotation['source_sha256'])
    extraction_physical=a.extraction_physical or a.physical
    frozen=json.loads((extraction_physical/'checks.json').read_text())
    if frozen['status']!='PASS':raise ValueError('tested extraction did not pass physical checks')
    # Historical source revisions may differ; their original hashes stay in
    # the archived receipt. The tested extraction artifacts must be unchanged.
    verify({str(extraction_physical/p):h for p,h in frozen['artifact_sha256'].items()})
    frozen_extract=json.loads((extraction_physical/'extraction/checks.json').read_text())
    if frozen_extract['source_sha256'].get(str((a.placement/'adc_sar_slice.gds').resolve()))!=digest(a.placement/'adc_sar_slice.gds'):
        raise ValueError('tested extraction belongs to another GDS')
    if digest(a.placement/'adc_sar_slice.gds')!=physical['source_sha256'][str((a.placement/'adc_sar_slice.gds').resolve())]:
        raise ValueError('geometry does not match physical checks')
    geometry=json.loads((a.placement/'placement.json').read_text())
    campaigns={}
    for flow,paths in [('schematic',a.schematic),('extracted',a.extracted)]:
        netlist=a.placement/'adc_sar_slice.schematic.spice' if flow=='schematic' else a.backannotation/'adc_sar_slice.extracted.spice'
        campaigns[flow]=[]
        for path,corner,temp in zip(paths,['mos_tt','mos_ss','mos_ff'],[27,125,-40]):
            checks,lowering=completed_case(path,netlist)
            if (lowering['corner'],lowering['temperature_C'])!=(corner,temp):raise ValueError('corner order mismatch')
            campaigns[flow].append(checks)
    evidence=out/'evidence';evidence.mkdir(exist_ok=True)
    def copy(source,target):
        target=out/target;target.parent.mkdir(parents=True,exist_ok=True);shutil.copy2(source,target)
    def archive_case(source,target):
        for name in ['checks.json','inputs.json','manifest.json','measurements.json','native.json','results.csv','decisions.csv','controls.csv','terminal_stress.csv','prefix-receipt.json']:
            if (source/name).exists():copy(source/name,Path('evidence')/target/name)
        # Independent ngspice references retain their exact causal decks and
        # tool logs, including the embedded geometry-matched subcircuit.
        for path in sorted(source.glob('prefix-*')):
            if path.suffix in ('.cir','.log'):copy(path,Path('evidence')/target/path.name)
        trace=source/'trace.csv'
        if trace.exists():
            dest=evidence/target/'trace.csv.gz';dest.parent.mkdir(parents=True,exist_ok=True)
            with dest.open('wb') as raw,gzip.GzipFile(filename='',mode='wb',fileobj=raw,mtime=0) as compressed:
                compressed.write(trace.read_bytes())
    for name in ['adc_sar_slice.gds','adc_sar_slice.def','adc_sar_slice.cells.lef','adc_sar_slice.lvs.cir','adc_sar_slice.schematic.spice']:
        copy(a.placement/name,name)
    copy(a.placement/'placement.json','adc_sar_slice.placement.json')
    copy(a.physical/'adc_sar_slice.odb','adc_sar_slice.odb')
    copy(a.backannotation/'adc_sar_slice.extracted.spice','adc_sar_slice.extracted.spice')
    for path,name in [(a.physical/'checks.json','physical.json'),(a.backannotation/'backannotation.json','backannotation.json'),(a.wire,'wire-resistance.json'),(a.parity,'schematic-parity.json')]:copy(path,Path('evidence')/name)
    copy(extraction_physical/'checks.json','evidence/tested-extraction-physical.json')
    copy(extraction_physical/'extraction/checks.json','evidence/tested-extraction.json')
    for source in [extraction_physical/'extraction/conserved.spice',*[extraction_physical/'extraction/named'/n for n in ('ExtractedAnalog.ext','ExtractedAnalog.res.ext','capacitance.spice')]]:
        dest=evidence/'tested-extraction'/(source.name+'.gz');dest.parent.mkdir(parents=True,exist_ok=True)
        with dest.open('wb') as raw,gzip.GzipFile(filename='',mode='wb',fileobj=raw,mtime=0) as compressed:
            compressed.write(source.read_bytes())
    for folder in ('drc','lvs','extraction'):
        for name in ['checks.json']:
            if (a.physical/folder/name).exists():copy(a.physical/folder/name,Path('evidence/physical')/folder/name)
    for name in ['drc.log','lvs.log','openroad.log']:
        copy(a.physical/name,Path('evidence/physical')/name)
    copy(a.physical/'drc/adc_sar_slice_adc_sar_slice_full.lyrdb','evidence/physical/drc.lyrdb')
    copy(a.physical/'lvs/adc_sar_slice.lvsdb','evidence/physical/lvs.lvsdb')
    for flow,paths in [('schematic',a.schematic),('extracted',a.extracted)]:
        for path,corner in zip(paths,['tt','ss','ff']):archive_case(path,flow+'-'+corner)
    for path in a.extra_case:archive_case(path,path.name)
    for path in a.log:copy(path,Path('evidence/regressions')/path.name)

    drc=physical['stages']['drc'];lvs=physical['stages']['lvs'];counts=annotation['lowering']['counts']
    revision=a.revision or digest(out/'adc_sar_slice.gds')[:12]
    text='\n'+MARKER+'\n\nMeasurements below identify the delivered '+revision+' geometry. Values are simulation/extraction results, not silicon measurements. Numerical precision is not a claim of foundry-qualified accuracy.\n'
    text+=table(['Physical check / measurement','Requirement','Measured result','Status'],[
        ['Full IHP DRC','0 violations; all decks complete',f"{drc['count']} violations / {drc['qualification']['categories']} categories",'PASS'],
        ['DRC completion','37 main tables + maximum/density/antenna','All enabled; no waivers','PASS'],
        ['Strict hierarchical LVS','All circuits/devices/ports matched',f"{lvs['matched_circuits']} circuits; {lvs['instantiated_devices']} devices; 16 ports",'PASS'],
        ['OpenROAD placement import','137 cells / 56 nets / 16 ports','137 / 56 / 16','PASS'],
        ['Occupied mask bounding box','Characterize',f"{geometry['width_um']:.2f} x {geometry['height_um']:.2f} um",'MEASURED'],
        ['Occupied bounding area','Characterize',f"{geometry['bounding_area_um2']/1e6:.7f} mm2",'MEASURED'],
        ['DEF die including 20 um margins','Characterize',' x '.join(f'{v:.2f}' for v in geometry['placement_view']['die_um'])+' um','MEASURED'],
        ['Placed inventory','C++ topology retained','59 MOS groups / 57 C structures / 21 R','PASS'],
        ['MOS fingers / physical MIM units','Geometry preserved',f"{annotation['junction']['devices']} / {counts['mim']}",'PASS'],
        ['Extracted wire resistors','Retain distributed device/C terminals',str(counts['R']),'PASS'],
        ['Nonzero parasitic capacitors','Retain coupling and storage',str(counts['C']),'PASS'],
        ['R3 physical resistor halves','Body adapter preserves midpoint RC',str(counts['rppd']),'MEASURED'],
        ['HV lengths at 3.3 V','N >= 0.6 um; P >= 0.5 um','0.6 / 0.5 um minimum','PASS'],
        ['HV finger width','0.3 through 10 um','All exported fingers in range','PASS']])
    text+=f"\nThe {lvs['instantiated_devices']} LVS devices include hierarchical guard/tap elements. They are not the flattened simulation inventory. Series MIM structures produce {counts['mim']} physical MIM units; {geometry['inventory']['resistor']} physical resistors become {counts['rppd']} R3 halves. Exact resistor-only elimination reduces {annotation['reduction']['original_resistors']:,} wire resistors to {counts['R']:,} without eliminating storage or compact-device terminals. {counts['zero_capacitors_omitted']} exactly zero capacitors are omitted; nonzero parasitics remain.\n"
    text+=table(['Layer','Block-window density (%)','PDK density result'],[[k,f'{v:.2f}','PASS'] for k,v in drc['qualification']['density_percent'].items()])
    text+='\nDensity acceptance uses the actual installed PDK deck, including local windows and exclusions; the percentages alone do not establish acceptance.\n'
    wires=json.loads(a.wire.read_text())['measurements'];groups={}
    for r in wires:groups.setdefault((r['port'],r['terminal']),[]).append(r['resistance_Ohm'])
    text+=table(['Extracted wire path','Minimum (ohm)','Maximum (ohm)','Requirement'],[[f'{p} -> {t}',f'{min(v):.6f}',f'{max(v):.6f}','Characterize; devices/C open'] for (p,t),v in groups.items()])
    text+='\nElectrical acceptance: acquisition <= 20 mV; hold peak-to-peak <= 20 mV; absolute code error <= 2 counts; zero unresolved decisions; >= 25 ps stable decision before evaluation ends; IO >= 3.0 V and core >= 1.08 V at the supply pins. Code error is measured against floor(256 * input / 3.3), clipped to 0..255. One count is 12.890625 mV.\n'
    text+=table(['Observed voltage','Logical net','Extracted probe node'],[[label,m['cpp_net'],m['extracted_node']] for label,m in annotation['observations'].items()])
    text+='\nThese are retained points on distributed conductors. Observation does not short the rest of each net or substitute ideal voltages at transistor terminals.\n'
    for flow in ['schematic','extracted']:
        cases=campaigns[flow]
        text+='\n**'+('Geometry-matched schematic' if flow=='schematic' else 'GDS-extracted connected slice')+'**, 20 ps maximum conversion step, five successive inputs per corner. '
        native=cases[0]['native']
        if 'startup_edge_maximum_step_s' in native:
            text+=f"The supply-ramp interval through {native['startup_edge_ends_s']*1e9:g} ns uses at most {native['startup_edge_maximum_step_s']*1e12:g} ps steps. Quiet warmup until 19 ns permits 100 ps steps.\n"
        else:text+='Startup before 19 ns permits 100 ps steps.\n'
        rows=[]
        for label,case in zip(['TT / 27 C','SS / 125 C','FF / -40 C'],cases):
            for r in case['measurements']['samples']:
                rows.append([label,f"{r['input_V']:.2f}",f"{r['acquisition_V']*1e3:.6f}",f"{r['hold_pp_V']*1e3:.6f}",f"{r['code']:.0f}/{r['ideal']:.0f}",f"{r['code_error']:.0f}",r['invalid_decisions'],f"{r['minimum_decision_margin_s']*1e12:.1f}",'PASS' if r['pass'] else 'FAIL'])
        text+=table(['Corner','Vin (V)','Acq (mV)','Hold pp (mV)','Code/ideal','Error','Invalid','Setup (ps)','Result'],rows)
        rows=[]
        for label,case in zip(['TT / 27 C','SS / 125 C','FF / -40 C'],cases):
            s=case['measurements']['samples']
            rows.append([label,f"{min(r['io_min_V'] for r in s):.6f}",f"{min(r['core_min_V'] for r in s):.6f}",f"{max(r['io_peak_A'] for r in s)*1e3:.3f}",f"{max(r['core_peak_A'] for r in s)*1e3:.3f}",f"{min(r['full_cycle_power_W'] for r in s)*1e3:.3f}..{max(r['full_cycle_power_W'] for r in s)*1e3:.3f}",f"{min(r['full_cycle_energy_J'] for r in s)*1e12:.3f}..{max(r['full_cycle_energy_J'] for r in s)*1e12:.3f}"])
        text+=table(['Corner','Min IO V','Min core V','Peak IO mA','Peak core mA','Power range mW','Energy range pJ'],rows)
    text+='\nEnergy integrates both supply sources over each complete 50 ns sample cycle, including acquisition, conversion and idle time. IO/core voltage minima are acceptance gates. Peak current, energy and power are characterization only: no project budget has been specified. These pin currents do not qualify individual contacts, vias or wires for electromigration.\n'
    stress=[]
    for flow,paths in [('schematic',a.schematic),('extracted',a.extracted)]:
        for corner,path in zip(['TT','SS','FF'],paths):
            rows=list(csv.DictReader((path/'terminal_stress.csv').open()))
            hv=[float(r['peak_V']) for r in rows if r['quantity']=='vgs_max' and float(r['model_limit_V'])==3]
            lv=[float(r['peak_V']) for r in rows if r['quantity']=='vgs_max' and float(r['model_limit_V'])<3]
            stress.append([flow,corner,f'{max(hv):.6f}',f'{max(lv):.6f}',sum(int(r['exceeded']) for r in rows),'EXCEEDED' if max(hv)>3.3 else 'Within 3.3 V screen'])
    text+=table(['Network','Corner','Max HV |Vgs| V','Max LV |Vgs| V','Raw card exceedances','3.3 V screen'],stress)
    parity=json.loads(a.parity.read_text())
    text+='\nRaw exceedances count device/quantity pairs whose recorded peak exceeds the card limit, not events or failed conversions. The documented HV 3.3 V maximum condition is specified at 27 C and the stated minimum lengths. Its strict terminal-voltage screen is exceeded. The raw PSP cards also contain 3.0 V HV gate/drain diagnostic limits and 1.6 V body diagnostics, with SWSOA disabled. Neither disabled diagnostics nor DRC acceptance permits declaring these overshoots safe. Transient lifetime limits and elevated/cold-temperature reliability remain unqualified.\n'
    text+=table(['Numerical / reference comparison','Requirement','Current result','Status'],[
        ['TT schematic native vs ngspice, 5 ps','Same code',str(parity['differences']['code']),'PASS' if parity['scalar_status']=='PASS' else 'FAIL'],
        ['Acquisition measurement difference','<= 1 mV',f"{parity['differences']['acquisition_V']*1e3:.6f} mV",parity['scalar_status']],
        ['Hold measurement difference','<= 1 mV',f"{parity['differences']['hold_pp_V']*1e3:.6f} mV",parity['scalar_status']],
        ['Decision setup difference','<= 50 ps',f"{parity['differences']['minimum_decision_margin_s']*1e12:.6f} ps",parity['scalar_status']],
        ['11 observed-node waveform peak','<= 20 mV',f"{parity['waveform']['peak_V']*1e3:.6f} mV",parity['waveform_status']],
        ['Worst observed-node waveform RMS','<= 1 mV',f"{parity['waveform']['rms_V']*1e3:.6f} mV",parity['waveform_status']]])
    worst,node=max(parity['waveform']['nodes'].items(),key=lambda item:item[1]['peak_V'])
    text+=f"\nThe largest reference discrepancy is on `{worst}` at {node['peak_time_s']*1e9:.6f} ns. The scalar comparison does not waive this pointwise waveform failure.\n"
    if a.refinement:
        refined=json.loads(a.refinement.read_text());copy(a.refinement,'evidence/extracted-refinement.json')
        text+='\n**Extracted TT, first 0.85 V conversion: 20 ps versus 5 ps.** Both traces cover the same 70 ns prefix, including startup and a full sample cycle. No waveform time shift is applied.\n'
        text+=table(['Refinement metric','Requirement','Measured difference','Status'],[
            ['Code','0 counts',f"{refined['differences']['code']:.0f} counts",'PASS' if refined['differences']['code']==0 else 'FAIL'],
            ['Acquisition','<= 1 mV',f"{refined['differences']['acquisition_V']*1e3:.6f} mV",'PASS' if refined['differences']['acquisition_V']<=.001 else 'FAIL'],
            ['Hold variation','<= 1 mV',f"{refined['differences']['hold_pp_V']*1e3:.6f} mV",'PASS' if refined['differences']['hold_pp_V']<=.001 else 'FAIL'],
            ['Stable decision margin','<= 50 ps',f"{refined['differences']['minimum_decision_margin_s']*1e12:.6f} ps",'PASS' if refined['differences']['minimum_decision_margin_s']<=50e-12 else 'FAIL'],
            ['11 observed-node waveform peak','<= 20 mV',f"{refined['waveform']['peak_V']*1e3:.6f} mV",refined['waveform_status']],
            ['Worst observed-node waveform RMS','<= 1 mV',f"{refined['waveform']['rms_V']*1e3:.6f} mV",refined['waveform_status']]])
    if a.notes:
        copy(a.notes,'evidence/report-notes.md');text+='\n'+a.notes.read_text()
    report=out/'pnr.md'
    if not report.exists():raise ValueError('pnr.md introduction must exist before updating measured tables')
    report.write_text(report.read_text().split(MARKER)[0].rstrip()+'\n'+text)
    manifest=dict(status='FAIL',qualified=False,geometry_sha256=digest(out/'adc_sar_slice.gds'),
        scope='physical checks pass; electrical failures and unqualified tests remain',
        artifacts={str(p.relative_to(out)):digest(p) for p in sorted(out.rglob('*')) if p.is_file() and '__pycache__' not in p.parts and p!=out/'manifest.json'})
    (out/'manifest.json').write_text(json.dumps(manifest,indent=2)+'\n')

if __name__=='__main__':
    p=argparse.ArgumentParser(description=__doc__)
    for name in ['placement','physical','backannotation','wire','parity','output']:p.add_argument('--'+name,type=Path,required=True)
    p.add_argument('--schematic',nargs=3,type=Path,required=True);p.add_argument('--extracted',nargs=3,type=Path,required=True)
    p.add_argument('--extra-case',action='append',type=Path,default=[])
    p.add_argument('--revision',help='human-readable geometry revision; defaults to its GDS hash')
    p.add_argument('--refinement',type=Path);p.add_argument('--notes',type=Path)
    p.add_argument('--extraction-physical',type=Path,help='frozen extraction used by the electrical cases, if different from the latest physical check run')
    p.add_argument('--log',type=Path,action='append',default=[])
    run(p.parse_args())
