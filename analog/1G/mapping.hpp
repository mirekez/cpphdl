class symbol_mapper {
public:
    static quartet map(unsigned point, unsigned subset) {
        if (point >= 64 || subset >= 8)
            throw diagnostic("E_VALUE", "PAM5 mapping requires point < 64 and subset < 8");
        return normal_constellation[point * 8 + subset];
    }
    static std::optional<unsigned> inverse(const quartet& symbol) {
        for (unsigned i = 0; i < normal_constellation.size(); ++i)
            if (normal_constellation[i] == symbol)
                return i;
        return std::nullopt;
    }
};
