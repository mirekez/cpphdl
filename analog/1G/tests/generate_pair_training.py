#!/usr/bin/env python3
"""Generate pair-acquisition stimuli from the independent Clause 40 oracle."""
import argparse
import hashlib
from pathlib import Path
from transmit_reference import Reference

source = Path(__file__).resolve().parent
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
rows = ['// Generated by tests/generate_pair_training.py from the independent transmitter oracle.',
        '#pragma once', '#include <array>', '#include <cstdint>',
        'struct PairTrainingStream {', '    bool master;', '    bool receiver_ready;',
        '    std::uint64_t seed;', '    std::array<std::uint16_t, 4096> words;', '};',
        'inline constexpr std::array<PairTrainingStream, 8> pair_training{{']
for master in (0, 1):
    for ready in (0, 1):
        for seed in (1, 0x123456789):
            reference = Reference(source)
            reference.reset(seed)
            words = [reference.step(0, 0, 0, master, 1, 0, ready, 0, 0, 0)[-1] for _ in range(4096)]
            rows.append(f'    {{{str(bool(master)).lower()}, {str(bool(ready)).lower()}, {seed}ULL, {{{{')
            for i in range(0, len(words), 16):
                rows.append('        ' + ', '.join(map(str, words[i:i + 16])) + ',')
            rows.append('    }}},')
rows.append('}};')
for path in [source / 'transmit_reference.py', *sorted(source.glob('pcs_*.csv'))]:
    rows.append('// Source SHA-256 ' + path.name + ': ' + hashlib.sha256(path.read_bytes()).hexdigest())
text = '\n'.join(rows) + '\n'
destination = source / 'pair_training.hpp'
if args.check:
    if not destination.is_file() or destination.read_text() != text:
        raise ValueError('stale pair training fixture; run generate_pair_training.py')
else:
    destination.write_text(text)
print('Checked' if args.check else 'Generated', '8 independent 4096-symbol training streams')
